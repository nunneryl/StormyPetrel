    r.slug                                AS slug,
    r.name                                AS name,
    r.tide_preference                     AS tide_preference,
    NULL::timestamptz                     AS created_at,
    NULL::timestamptz                     AS updated_at
  FROM roster r
  LEFT JOIN spots s ON s.slug = r.slug
 WHERE s.slug IS NULL

UNION ALL

-- The reverse direction, so this answers whether the divergence is one-way or both.
-- created_at / updated_at are included here because the table has them and the roster does
-- not: the roster holds no timestamp of any kind (its only date-shaped field is
-- disambiguated_at, present on 2 records), so when a row appeared is knowable only from here.
SELECT
    'spots row with NO roster entry'      AS direction,
    s.slug                                AS slug,
    s.name                                AS name,
    s.tide_preference                     AS tide_preference,
    s.created_at                          AS created_at,
    s.updated_at                          AS updated_at
  FROM spots s
  LEFT JOIN roster r ON r.slug = s.slug
 WHERE r.slug IS NULL

 ORDER BY direction, slug;
