-- Which roster entries are missing from the spots table, and vice versa.
--
-- WHY THIS EXISTS. pipeline/spots_enriched.json holds 648 records; the spots table holds
-- 646. The gap is entirely in tide_preference = 'mid' (367 in the roster, 365 in the table),
-- so two roster spots have no row. This finds them by name rather than by guessing.
--
-- THE JOIN KEY IS slug, DERIVED FROM name — and it has to be derived, because the roster
-- carries NO identifier at all. Verified against all 648 records: no `slug`, no `id`, no
-- `spot_id`, no `osm_id`. The only fields that could identify a row are `name` and
-- (`lat`, `lng`).
--
-- slug is the right derivation because it is what the database itself keys on:
-- db_import.py:126 writes "slug": _slugify(spot.get("name") or "") and db_import.py:573
-- upserts with on_conflict="slug". So a roster entry and a table row correspond exactly when
-- their slugs match — by construction, not by convention.
--
-- The slugs below were produced by the same rule as db_import._slugify (pipeline/db_import.py
-- :52-57): lowercase, replace every run of non-[a-z0-9] with a single hyphen, strip leading
-- and trailing hyphens. All 648 slugs are distinct and none is empty, so the key is sound.
--
-- NOT id. spots.id is `SERIAL PRIMARY KEY` (001_initial_schema.sql:12), and db_import treats
-- it as database-managed — _DB_MANAGED_COLUMNS at db_import.py:191 is {id, geom, created_at,
-- updated_at} and the importer never writes it. Large non-sequential values like 203293 are
-- therefore a serial inflated by churn, not an external manifest id: Postgres consumes a
-- sequence value on every INSERT attempt including ones that hit ON CONFLICT, so repeated
-- full-roster upserts burn ~648 numbers each and the counter runs far ahead of the row count.
-- Nothing outside the database knows those ids, and the roster cannot be joined on them.
--
-- Names are inlined with '' escaping; 10 of the 648 contain an apostrophe.
--
-- Paste whole into the Supabase SQL editor. Read-only — SELECT only, no writes.

